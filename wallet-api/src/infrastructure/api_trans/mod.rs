//! ============================================================================
//! 交易流程统一终局模型（FACT → TERMINAL_REASON → SIDE EFFECTS）
//! ============================================================================
//!
//! 本文档用于定义：
//!
//! - 什么是【终局事实】
//! - 一个交易**只能进入一个终局**
//! - 每个终局只允许触发**固定集合**的副作用
//!
//! Scanner / Worker / Recover / MQTT
//! 均不得突破本规则。
//!
//! ============================================================================
//! 一、终局的本质定义（铁律）
//! ============================================================================
//!
//! 【终局（Terminal）】定义：
//!
//! 一旦某个不可逆事实成立，
//! 系统即可 100% 确定：
//!
//! - 该交易不会再进入新的业务阶段
//! - 不会再产生新的链上行为
//! - 只允许补发“通知类副作用”
//!
//! ⚠️ 一个交易在生命周期中：
//! - 只能进入一个终局
//! - 终局一旦成立，不可撤销
//!
//! ============================================================================
//! 二、终局类型总表（唯一权威）
//! ============================================================================

//! ---------------------------------------------------------------------------
//! TERMINAL #1：链上结果已确定（On-chain Result Finalized）
//! ---------------------------------------------------------------------------
//!
//! 【终局事实】
//! transaction_time IS NOT NULL
//!
//! 【事实来源】
//! - MQTT TxRes（后端扫链）
//! - Recover（通过 tx_hash 查到最终结果）
//!
//! 【语义】
//! - 链上执行已完成
//! - 成功 / 失败均属于该终局
//!
//! 【允许的副作用】
//! - scan_confirmed_need_tx_res_ack
//! - finished_at
//!
//! 【禁止行为】
//! - 再次 broadcast
//! - 再次 build
//! - 再次构造 raw_tx
//!

//! ---------------------------------------------------------------------------
//! TERMINAL #2：构建阶段确认失败（手续费不足）
//! ---------------------------------------------------------------------------
//!
//! 【终局事实】
//! build_blocked_at IS NOT NULL
//! AND need_service_fee = true
//!
//! 【事实来源】
//! - Build 阶段本地判定
//!
//! 【语义】
//! - 链上执行从未发生
//! - 该交易在业务上已失败
//!
//! 【允许的副作用】
//! - scan_need_tx_exec_receipt_upload（失败回执）
//! - finished_at
//!
//! 【禁止行为】
//! - broadcast
//! - recover
//! - 等待 MQTT
//! - 写入 transaction_time
//!

//! ---------------------------------------------------------------------------
//! TERMINAL #3：显式放弃 / 系统终止（可选）
//! ---------------------------------------------------------------------------
//!
//! 【终局事实】
//! finished_at IS NOT NULL
//! AND transaction_time IS NULL
//! AND build_blocked_at IS NULL
//!
//! 【语义】
//! - 非链上失败
//! - 非手续费失败
//! - 由业务或系统策略终止
//!
//! 【允许的副作用】
//! - 无（纯终止）
//!
//! ⚠️ 若未来启用，必须明确记录终止原因字段
//!

//! ============================================================================
//! 三、非终局事实（只能作为推进条件）
//! ============================================================================

//! last_broadcast_at
//! ---------------------------------------------------------------------------
//! - 行为事实
//! - 表示“我尝试发过链”
//! - ❌ 永远不是终局
//!

//! raw_tx
//! ---------------------------------------------------------------------------
//! - 构建中间产物
//! - ❌ 永远不是终局
//!

//! tx_exec_receipt_uploaded_at
//! ---------------------------------------------------------------------------
//! - 副作用完成标记
//! - ❌ 永远不是终局
//!

//! ============================================================================
//! 四、Scanner 推进顺序的终局感知规则
//! ============================================================================

//! Scanner 在每一轮扫描中，必须遵循以下顺序：
//!
//! 1️⃣ 先判断是否已进入任一 TERMINAL
//!     - 若是：
//!       - 只允许执行该 TERMINAL 允许的副作用
//!       - 严禁推进构建 / 广播 / recover
//!
//! 2️⃣ 若未进入 TERMINAL，才允许：
//!     - build
//!     - broadcast
//!     - receipt upload
//!
//! ---------------------------------------------------------------------------
//! 推荐实现策略：
//!
//! - 所有 scan_xxx() 内部第一行：
//!   if is_terminal() { return; }
//!

//! ============================================================================
//! 五、与「归集 / 手续费」流程的统一解释
//! ============================================================================
//!
//! - 归集成功 / 失败：
//!   → TERMINAL #1（链上结果已确定）
//!
//! - 手续费不足：
//!   → TERMINAL #2（构建阶段失败）
//!
//! 二者在系统层级：
//! - 没有“高低级之分”
//! - 都是**平等的终局**
//!
//! 差异只体现在：
//! - 终局事实不同
//! - 允许的副作用不同
//!
//! ============================================================================
//! 六、最终不可违反的三条宪法级规则
//! ============================================================================
//!
//! 1️⃣ 一个交易，只能进入一个终局
//! 2️⃣ 终局一旦成立，只能补副作用，不能改事实
//! 3️⃣ Scanner 永远不制造终局，只消费终局
//!
//! ============================================================================
//! END
//! ============================================================================
