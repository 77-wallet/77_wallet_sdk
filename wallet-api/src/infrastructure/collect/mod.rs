//! # 后台任务并发模型说明（请务必阅读）
//!
//! 本模块负责【归集交易上报】相关的后台任务处理，
//! 其并发模型是 **刻意设计过的**，不是临时写法。
//!
//! ------------------------------------------------------------
//! ## 一、我们在解决什么问题？
//!
//! 后台任务系统需要同时满足：
//!
//! 1. **高并发吞吐**
//!    - 不同地址（from_addr）的任务应当并行执行
//!
//! 2. **地址级严格串行**
//!    - 同一个地址的任务 **绝不能并发**
//!    - 否则会导致：nonce 错乱 / 状态覆盖 / 重复上报
//!
//! 3. **可控的生命周期**
//!    - 不活跃地址不应永久占用内存
//!    - 系统不能维护一个“永不释放的锁表”
//!
//! ------------------------------------------------------------
//! ## 二、当前并发模型（非常重要）
//!
//! ### 并发粒度原则
//!
//! > **并发的最小粒度是「地址」**
//!
//! - 地址之间：并行
//! - 同一地址内：严格串行
//!
//! ------------------------------------------------------------
//! ## 三、实现方式
//!
//! 当前采用：
//!
//! - `DashMap<Address, Weak<Semaphore>>`
//! - `Semaphore(1)` 作为地址级串行保证
//!
//! 各组件职责：
//!
//! - **DashMap**
//!   - 并发安全地管理「地址 → 锁」的映射
//!
//! - **Semaphore(1)**
//!   - 保证同一地址一次只执行一个任务
//!
//! - **Weak**
//!   - 当某个地址不再有任务执行时，
//!     对应的锁会被自动回收，避免内存泄漏
//!
//! ⚠️ 注意：
//! - 锁只用于【并发控制】
//! - **绝不保存任何业务状态**
//!
//! ------------------------------------------------------------
//! ## 四、为什么不用全局 Mutex？（禁止）
//!
//! ```ignore
//! static GLOBAL_LOCK: Mutex<()> = Mutex::new(());
//! ```
//!
//! 原因：
//! - 会把所有地址串行化
//! - 一个慢地址会拖垮整个系统
//! - 吞吐量无法随地址数扩展
//!
//! 👉 这是明确禁止的实现方式
//!
//! ------------------------------------------------------------
//! ## 五、业务代码必须遵守的规则
//!
//! ### ✅ 允许
//!
//! - 只通过统一逻辑获取地址级执行权
//! - 在获得 permit 后执行业务逻辑
//! - 任务结束后自然释放（RAII）
//!
//! ```rust,ignore
//! let _permit = address_lock.acquire().await;
//! do_work().await;
//! ```
//!
//! ------------------------------------------------------------
//! ### ❌ 严格禁止（非常重要）
//!
//! #### 1️⃣ 不要在业务代码中私自创建锁
//!
//! ```rust,ignore
//! // ❌ 禁止
//! let lock = Mutex::new(());
//! ```
//!
//! 否则会破坏地址级串行保证，
//! 产生极难排查的并发 Bug。
//!
//! ------------------------------------------------------------
//! #### 2️⃣ 不要在锁内跨 await 持有其他 Mutex
//!
//! ```rust,ignore
//! // ❌ 高危
//! let guard = map.lock().await;
//! call_remote().await;
//! ```
//!
//! 可能导致：
//! - 死锁
//! - 全局阻塞
//! - 隐性性能雪崩
//!
//! ------------------------------------------------------------
//! #### 3️⃣ 不要在地址锁内做长时间阻塞
//!
//! ```rust,ignore
//! // ❌ 避免
//! sleep(Duration::from_secs(30)).await;
//! ```
//!
//! 会阻塞该地址下的所有后续任务。
//!
//! ------------------------------------------------------------
//! ## 六、什么时候需要升级为 Actor？
//!
//! 当前模型 **刻意不使用 Actor**，以保持简单性。
//!
//! 但在以下情况下，必须进入 Actor 改造评估：
//!
//! - 需要维护地址级长期状态（nonce / pending tx 等）
//! - 出现多步骤、强顺序依赖的地址级工作流
//! - 需要主动取消 / 合并 / 丢弃地址级任务
//!
//! 👉 详细标准请参考：
//! 《何时必须从 DashMap + Weak 升级到 Actor》设计文档
//!
//! ------------------------------------------------------------
//! ## 七、重要共识（写给未来维护者）
//!
//! > 当前并发模型不是“临时方案”，
//! > 而是在【无状态前提下】
//! > 最简单、最安全、最可控的实现。
//!
//! > 如果你觉得“可以顺手改一下”，
//! > 请先假设：
//! > **这个模块已经在高并发下稳定运行过。**
//!
//! ------------------------------------------------------------
